import pandas as pd
import logging

logging.basicConfig(level=logging.INFO, format='%(levelname)s: %(message)s')

def profilename_financeiro(df):
    logging.info("Iniciando Data Profiling especializado...")

    if df.empty:
        logging.error("O DataFrame extraído está vazio.")
        return df

    # Validação de valores nulos
    nulos_valor = df['Valor'].isnull().sum()
    if nulos_valor > 0:
        logging.warning(f"Detectados {nulos_valor} registros sem valor.")

    # Verificação de datas
    # Como a coluna 'Dias' contém apenas o número do dia, vamos criar a data correta
    # Baseado no nome do arquivo 'gastos harpia 2026.xlsx'
    df['Data'] = pd.to_datetime(df['Data'].apply(lambda x: f"2026-01-{int(x):02d}" if pd.notnull(x) else x), errors='coerce')

    datas_invalidas = df['Data'].isnull().sum()
    if datas_invalidas > 0:
        logging.warning(f"Detectadas {datas_invalidas} datas inválidas.")

    # Duplicados
    duplicados = df.duplicated().sum()
    logging.info(f"Transações duplicadas identificadas: {duplicados}")

    print("\nResumo dos Dados Perfilados:")
    print(df.head())
    return df

# Carregamento da planilha
df_raw = pd.read_excel("gastos harpia 2026.xlsx", header=None)

# Localiza a linha que contém os cabeçalhos 'Dias' e 'Gastos'
header_row_idx = 0
for i, row in df_raw.iterrows():
    if 'Gastos' in row.values and 'Dias' in row.values:
        header_row_idx = i
        break

# Extração e Limpeza
df_temp = df_raw.copy()
df_temp.columns = df_raw.iloc[header_row_idx]
df_temp = df_temp.iloc[header_row_idx + 1:].reset_index(drop=True)

col_data = 'Dias'
col_valor = 'Gastos'

if col_data in df_temp.columns and col_valor in df_temp.columns:
    # Filtra apenas linhas onde há um dia definido e remove valores nulos de Gastos
    df_consolidado = df_temp[[col_data, col_valor]].copy()
    df_consolidado = df_consolidado.dropna(subset=[col_data])
