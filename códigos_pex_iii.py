def profilename_financeiro_final(df):
    logging.info("--- Iniciando Data Profiling do Fluxo de Caixa (Harpia 2026) ---")

    # 1. Validação de valores nulos nas colunas críticas
    nulos_valor = df['Valor'].isnull().sum()
    if nulos_valor > 0:
        logging.warning(f"Alerta: Detectados {nulos_valor} registros sem valor monetário.")
    else:
        logging.info("Sucesso: Nenhum valor monetário nulo encontrado.")

    # 2. Verificação do padrão de datas
    # Como já tratamos a data na leitura, verificamos se a conversão resultou em NaT
    datas_invalidas = df['Data'].isnull().sum()
    if datas_invalidas > 0:
        logging.error(f"Erro: Inconsistência de tipo em {datas_invalidas} datas. Requer normalização ETL.")
    else:
        logging.info(f"Sucesso: Todas as {len(df)} datas foram validadas corretamente.")

    # 3. Análise de duplicidade de transação
    # Verifica se existem linhas idênticas para a mesma data, descrição e valor
    duplicados = df.duplicated(subset=['Data', 'Descricao', 'Valor']).sum()
    if duplicados > 0:
        logging.info(f"Aviso: Transações duplicadas identificadas: {duplicados}")
    else:
        logging.info("Sucesso: Nenhuma transação duplicada encontrada.")

    # 4. Sumário estatístico simples
    print("\n--- Estatísticas de Gastos ---")
    print(f"Total de Gastos no período: R$ {df['Valor'].astype(float).sum():.2f}")
    print(f"Maior gasto registrado: R$ {df['Valor'].astype(float).max():.2f}")

    return df

